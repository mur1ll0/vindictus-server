-- Source ReservedName/ReservedTitle/CharacterNameLog: no FKs, lossless nvarchar(50).
CREATE TABLE game_reserved_names (
 row_id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 MINVALUE -2147483648 MAXVALUE 2147483647) PRIMARY KEY,
 nexon_id_utf16 BYTEA NOT NULL CHECK(octet_length(nexon_id_utf16)<=100 AND octet_length(nexon_id_utf16)%2=0),
 nexon_sn INTEGER NOT NULL,
 character_name_utf16 BYTEA NOT NULL CHECK(octet_length(character_name_utf16)<=100 AND octet_length(character_name_utf16)%2=0),
 created BOOLEAN NOT NULL
);
CREATE TABLE game_reserved_titles (
 row_id INTEGER PRIMARY KEY,
 nexon_id_utf16 BYTEA NOT NULL CHECK(octet_length(nexon_id_utf16)<=100 AND octet_length(nexon_id_utf16)%2=0),
 nexon_sn INTEGER NOT NULL,
 title_id INTEGER NOT NULL,
 title_given BOOLEAN NOT NULL
);
CREATE TABLE game_character_name_logs (
 id BIGINT NOT NULL,
 old_character_name_utf16 BYTEA NOT NULL CHECK(octet_length(old_character_name_utf16)<=100 AND octet_length(old_character_name_utf16)%2=0),
 new_character_name_utf16 BYTEA NOT NULL CHECK(octet_length(new_character_name_utf16)<=100 AND octet_length(new_character_name_utf16)%2=0),
 log_date_units300 BIGINT NOT NULL DEFAULT (floor((extract(epoch FROM clock_timestamp()) + 2208988800)*300+0.5)::BIGINT)
 CHECK(log_date_units300 BETWEEN -1391644800000 AND 76683386879999),
 PRIMARY KEY(id,log_date_units300)
);
