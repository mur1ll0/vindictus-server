-- Recovered UserInfo/UserProducts/UserCareInfo contracts; source has no FKs/defaults.
CREATE TABLE game_user_info (
 nexon_sn INTEGER PRIMARY KEY,
 last_login_cid BIGINT,
 prologue_played BOOLEAN NOT NULL
);
CREATE TABLE game_user_products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nexon_sn INTEGER NOT NULL,
 product_name_utf16 BYTEA NOT NULL CHECK(octet_length(product_name_utf16)<=256 AND octet_length(product_name_utf16)%2=0),
 argument_utf16 BYTEA CHECK(argument_utf16 IS NULL OR (octet_length(argument_utf16)<=256 AND octet_length(argument_utf16)%2=0)),
 expire_time_ticks BIGINT CHECK(expire_time_ticks BETWEEN 0 AND 3155378975999999999)
);
CREATE INDEX game_user_products_owner ON game_user_products(nexon_sn);
CREATE TABLE game_user_care_info (
 uid INTEGER PRIMARY KEY,
 kind SMALLINT NOT NULL CHECK(kind BETWEEN 0 AND 255),
 state SMALLINT NOT NULL,
 last_update_units300 BIGINT NOT NULL CHECK(last_update_units300 BETWEEN -1391644800000 AND 76683386879999)
);
