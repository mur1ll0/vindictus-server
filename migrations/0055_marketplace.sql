-- Marketplace (PlayerService TradeSystem, B5 mercado) over the heroesMarketPlace layout:
-- TradeItem, TradeItem_Attribute, TradeCategoryInfo, TradeOrder, TradeGold, the history
-- tables, TradeItem_Expire and TradeItem_Statistics, plus TradeLog of the log database.
-- Every backup table is empty (row_counts 0 in study_heroesMarketPlace.schema.json), so no
-- legacy rows are imported. datetime2 columns are DateTime ticks (UTC, as GETUTCDATE());
-- the *_working and Search_Working tables are scratch space of the procedures and are not
-- kept: each procedure runs as one statement set in one transaction here. No foreign keys,
-- as the source schema.
CREATE TABLE game_trade_category_info(
 item_class_seq INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 trade_category TEXT NOT NULL CHECK(length(trade_category)<=100),
 trade_category_sub TEXT NOT NULL CHECK(length(trade_category_sub)<=100),
 item_class TEXT NOT NULL CHECK(length(item_class)<=50),
 required_level INTEGER NOT NULL DEFAULT 0,
 UNIQUE(item_class, trade_category, trade_category_sub, required_level)
);
CREATE TABLE game_trade_items(
 tid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cid BIGINT NOT NULL,
 character_name TEXT NOT NULL CHECK(length(character_name)<=100),
 item_id BIGINT NOT NULL,
 trade_category TEXT NOT NULL CHECK(length(trade_category)<=100),
 trade_category_sub TEXT NOT NULL CHECK(length(trade_category_sub)<=100),
 item_class TEXT NOT NULL CHECK(length(item_class)<=50),
 required_level INTEGER NOT NULL,
 item_count INTEGER NOT NULL,
 item_price INTEGER NOT NULL,
 open_ticks BIGINT NOT NULL,
 close_ticks BIGINT NOT NULL,
 item_class_seq INTEGER NOT NULL,
 attribute_ex TEXT CHECK(length(attribute_ex)<=4096),
 color1 INTEGER,
 color2 INTEGER,
 color3 INTEGER,
 anti_bind INTEGER,
 max_armor_condition_mod INTEGER,
 armor_condition INTEGER,
 trade_type SMALLINT CHECK(trade_type BETWEEN 0 AND 255)
);
CREATE INDEX game_trade_items_cid ON game_trade_items(cid, close_ticks);
CREATE INDEX game_trade_items_close ON game_trade_items(close_ticks);
CREATE INDEX game_trade_items_category ON game_trade_items(lower(trade_category), lower(trade_category_sub), required_level);
CREATE INDEX game_trade_items_class ON game_trade_items(lower(item_class));
-- AddTradeItem inserts the DetailOption rows (Type, Value) of TradeManager.MakeDetailOption.
CREATE TABLE game_trade_item_attributes(
 id BIGSERIAL PRIMARY KEY,
 tid BIGINT NOT NULL,
 type TEXT NOT NULL CHECK(length(type)<=20),
 value INTEGER NOT NULL,
 log_ticks BIGINT NOT NULL
);
CREATE INDEX game_trade_item_attributes_tid ON game_trade_item_attributes(tid);
-- JobExpireTradeItem moves closed registrations here; ExpiredTradeItem returns them.
CREATE TABLE game_trade_items_expired(
 tid BIGINT PRIMARY KEY,
 cid BIGINT NOT NULL,
 character_name TEXT NOT NULL,
 item_id BIGINT NOT NULL,
 trade_category TEXT,
 trade_category_sub TEXT,
 item_class TEXT NOT NULL,
 required_level INTEGER,
 item_count INTEGER NOT NULL,
 item_price INTEGER NOT NULL,
 open_ticks BIGINT NOT NULL,
 close_ticks BIGINT NOT NULL,
 item_class_seq INTEGER,
 attribute_ex TEXT,
 color1 INTEGER,
 color2 INTEGER,
 color3 INTEGER,
 anti_bind INTEGER,
 max_armor_condition_mod INTEGER,
 armor_condition INTEGER,
 trade_type SMALLINT
);
CREATE INDEX game_trade_items_expired_cid ON game_trade_items_expired(cid);
-- TradeItem_History.Status: 1 added, 2 bought (ItemCount is what was left), 3 canceled,
-- 4 expired and returned.
CREATE TABLE game_trade_item_history(
 hid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tid BIGINT NOT NULL,
 cid BIGINT NOT NULL,
 character_name TEXT NOT NULL,
 item_id BIGINT NOT NULL,
 trade_category TEXT,
 trade_category_sub TEXT,
 item_class TEXT NOT NULL,
 required_level INTEGER,
 item_count INTEGER NOT NULL,
 item_price INTEGER NOT NULL,
 open_ticks BIGINT NOT NULL,
 close_ticks BIGINT NOT NULL,
 item_class_seq INTEGER,
 attribute_ex TEXT,
 color1 INTEGER,
 color2 INTEGER,
 color3 INTEGER,
 anti_bind INTEGER,
 max_armor_condition_mod INTEGER,
 armor_condition INTEGER,
 status SMALLINT NOT NULL DEFAULT 0,
 log_ticks BIGINT,
 trade_type SMALLINT,
 buy_count INTEGER,
 journal_id BIGINT
);
CREATE INDEX game_trade_item_history_tid ON game_trade_item_history(tid);
CREATE INDEX game_trade_item_history_avg ON game_trade_item_history(status, log_ticks);
CREATE TABLE game_trade_orders(
 oid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tid BIGINT NOT NULL,
 item_count INTEGER NOT NULL,
 buyer_cid BIGINT,
 buy_count INTEGER,
 log_ticks BIGINT NOT NULL
);
-- The seller's gold of each purchase until MyGold mails it.
CREATE TABLE game_trade_gold(
 gid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cid BIGINT NOT NULL,
 tid BIGINT NOT NULL,
 oid BIGINT NOT NULL,
 gold INTEGER NOT NULL
);
CREATE INDEX game_trade_gold_cid ON game_trade_gold(cid);
-- TradeGold_History.Status: 1 sold, 2 collected.
CREATE TABLE game_trade_gold_history(
 ghid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 gid BIGINT NOT NULL,
 cid BIGINT NOT NULL,
 tid BIGINT NOT NULL,
 oid BIGINT NOT NULL,
 gold INTEGER NOT NULL,
 status SMALLINT NOT NULL DEFAULT 0,
 log_ticks BIGINT
);
-- JobTradeItemAvgPrice output read by TradeItemAvgPriceList.
CREATE TABLE game_trade_item_statistics(
 id BIGSERIAL PRIMARY KEY,
 item_class TEXT NOT NULL,
 attribute_ex TEXT,
 min_price INTEGER NOT NULL,
 max_price INTEGER NOT NULL,
 buy_count BIGINT NOT NULL,
 sales BIGINT NOT NULL,
 last_update_ticks BIGINT NOT NULL
);
-- TradeLogger: AddTradeLog(Event, TID, CID, OID, ExtraInfomation) of the log database.
CREATE TABLE game_trade_logs(
 id BIGSERIAL PRIMARY KEY,
 logged_ticks BIGINT NOT NULL,
 event INTEGER NOT NULL,
 tid BIGINT,
 cid BIGINT,
 oid BIGINT,
 extra TEXT CHECK(length(extra)<=1024)
);
